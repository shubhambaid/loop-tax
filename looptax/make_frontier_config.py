"""Phase 3, >= 16 GB frontier (review 2026-11-27): keep the native NVFP4 experts, tune everything else.

Source: the hybrid GGUF (`looptax.make_hybrid`): original NVFP4 experts of blocks 0-19 bit for bit, all other tensors
BF16 from the release. Knobs:
  coda experts (blocks 20-23, MXFP8 in the release): gate_up and down types
  attention: BF16 in the most sensitive blocks (attention-only scan: 11, 12, 16, 17, then 6 and 10), Q8_0 or lower
             elsewhere
  small projections (attn_sink_proj, attn_*_conv_proj, 1.8M params): BF16, as in unsloth's file
  token_embd / output: Q8_0 or Q6_K
Target to beat: unsloth UD-Q4_K_M (16.6 GB). `unsloth-like` rebuilds that layout from our source as a control.
Every recipe is measured against the NVFP4 reference and the BF16 logits.

    python -m looptax.make_frontier_config --out configs/phase3_frontier.yaml
"""

from __future__ import annotations

import argparse
import re

import yaml

from . import recipes as R

SRC = "models/Inkling-2-Mini-hybrid.gguf"
S4 = [11, 12, 16, 17]
S6 = [6, 10, 11, 12, 16, 17]
SMALL = ("attn_sink_proj", "attn_k_conv_proj", "attn_v_conv_proj")


def tensor_type(name: str, dims: list[int], ref_type: str, r: dict) -> str | None:
    """Type of one tensor under recipe r; None = not quantizable (kept as in the source)."""
    if ref_type == "F32" or not name.endswith(".weight"):
        return None
    if name == "token_embd.weight":
        return r.get("embd", "Q8_0")
    if name == "output.weight":
        return r.get("output", "Q8_0")
    m = re.match(r"blk\.(\d+)\.(.+)\.weight", name)
    b, suf = int(m.group(1)), m.group(2)
    if suf in ("ffn_gate_up_exps", "ffn_down_exps"):
        if b < 20:
            return "NVFP4"
        return r["coda_gu"] if suf == "ffn_gate_up_exps" else r["coda_down"]
    if suf in SMALL:
        return "BF16"
    return r.get("attn_hi_type", "BF16") if b in r.get("attn_hi", []) else r.get("attn_lo", "Q8_0")


def build(vid: str, r: dict, table) -> dict:
    over, size = [], 0
    for t in table:
        typ = tensor_type(t["name"], t["dims"], t["type"], r)
        eff = t["type"] if typ is None else R.effective_type(typ, t["dims"][0])
        size += R.nbytes(eff, t["dims"])
        if typ is not None and typ != "Q8_0":
            over.append("^" + re.escape(t["name"]) + "$=" + typ.lower())
    return {"id": vid, "family": "frontier", "ftype": "Q8_0", "pure": True, "overrides": over,
            "est_gb": round(size / 1e9, 3), "recipe": {k: v for k, v in r.items()}}


RECIPES = {
    # control: unsloth's layout (coda gate_up Q5_K, coda down Q8_0, small projections BF16), from our source
    "unsloth-like": {"coda_gu": "Q5_K", "coda_down": "Q8_0"},
    # extra bits on the attention of the most sensitive blocks, same experts as unsloth
    "s4-bf16": {"coda_gu": "Q5_K", "coda_down": "Q8_0", "attn_hi": S4},
    "s6-bf16": {"coda_gu": "Q5_K", "coda_down": "Q8_0", "attn_hi": S6},
    # pay for the attention bits with cheaper coda down experts (coda experts are the least sensitive in the scan)
    "s6-bf16-down-q5_1": {"coda_gu": "Q5_K", "coda_down": "Q5_1", "attn_hi": S6},
    "s4-bf16-gu-q6k-down-q5_1": {"coda_gu": "Q6_K", "coda_down": "Q5_1", "attn_hi": S4},
    # all attention BF16, coda experts trimmed
    "attn-bf16-down-q5_1": {"coda_gu": "Q5_K", "coda_down": "Q5_1", "attn_hi": list(range(24))},
    # smaller: sensitive attention BF16, other attention Q6_K, embeddings Q6_K, coda down Q5_1
    "s6-bf16-rest-q6k": {"coda_gu": "Q5_K", "coda_down": "Q5_1", "attn_hi": S6, "attn_lo": "Q6_K", "embd": "Q6_K"},
}


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="configs/phase3_frontier.yaml")
    a = ap.parse_args(argv)
    table = R.load_table()
    vs = [build(k, r, table) for k, r in RECIPES.items()]
    cfg = {
        "experiment": "phase3-frontier",
        "reference": {"id": "ref-nvfp4", "model": "models/Inkling-2-Mini-NVFP4.gguf"},
        "source": SRC,
        "imatrix": "models/imatrix.gguf",
        "imatrix_default": True,
        "eval": {"dir": "data/eval", "ctx": 2048, "domains": {"wikitext": 8, "code": 4, "multilingual": 4}},
        "llama": {"ngl": 99},
        "bench": {"pp": 512, "tg": 128, "reps": 3},
        "keep_variants": False,
        "extra_refs": [{"id": "ref-bf16"}],
        "variants": vs,
    }
    with open(a.out, "w") as f:
        f.write("# generated by python -m looptax.make_frontier_config; do not edit by hand\n")
        yaml.safe_dump(cfg, f, sort_keys=False, width=240)
    for v in vs:
        print(f"{v['id']:28s} {v['est_gb']:7.3f} GB  {len(v['overrides'])} overrides")


if __name__ == "__main__":
    main()
