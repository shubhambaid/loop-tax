"""Generate the Phase 2 per-block sensitivity scan config.

Every variant is the reference file with exactly one physical block (or one tensor family in one block) requantized
to a low-bit type. All other tensors keep the reference type, and llama-quantize copies a tensor byte for byte when its
target type equals its current type, so the only difference from the reference is the target block. The `identity`
variant applies no change and must give KL = 0 exactly: it checks the pipeline.

    python -m looptax.make_scan_config --out configs/phase2_scan.yaml
"""

from __future__ import annotations

import argparse

import yaml

N_BLOCKS = 24
NVFP4_EXPERT_BLOCKS = range(0, 20)   # reference keeps the original NVFP4 experts here; blocks 20-23 experts are Q8_0
FAMILIES = {
    "block": r"",                               # every quantizable weight in the block
    "experts": r"ffn_(gate_up|down)_exps\.",
    "attn": r"attn_",
}


def keep_reference_overrides() -> list[str]:
    """Pin every tensor that is not the target to its reference type (base ftype Q8_0 covers the Q8_0 ones)."""
    blocks = "|".join(str(b) for b in NVFP4_EXPERT_BLOCKS)
    return [rf"^blk\.({blocks})\.ffn_(gate_up|down)_exps\.weight$=nvfp4"]


def variant(block: int | None, qtype: str, family: str = "block") -> dict:
    overrides = []
    if block is not None:
        overrides.append(rf"^blk\.{block}\.{FAMILIES[family]}.*weight$={qtype.lower()}")
    overrides += keep_reference_overrides()     # first matching pattern wins, so the target goes first
    vid = "identity" if block is None else f"{family}{block:02d}-{qtype.lower()}"
    return {"id": vid, "ftype": "Q8_0", "pure": True, "overrides": overrides, "bench": False,
            "block": block, "family": family if block is not None else None, "qtype": qtype if block is not None else None}


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="configs/phase2_scan.yaml")
    ap.add_argument("--types", nargs="+", default=["Q2_K", "Q3_K"])
    ap.add_argument("--family-blocks", nargs="*", type=int, default=[2, 5, 8, 11, 14, 17, 20, 23],
                    help="blocks that also get the per-family (experts / attn) breakdown")
    ap.add_argument("--family-type", default="Q2_K")
    a = ap.parse_args(argv)
    variants = [variant(None, "")]
    for qt in a.types:
        variants += [variant(b, qt) for b in range(N_BLOCKS)]
    for fam in ("experts", "attn"):
        variants += [variant(b, a.family_type, fam) for b in a.family_blocks]
    cfg = {
        "experiment": "phase2-scan",
        "reference": {"id": "ref-nvfp4", "model": "models/Inkling-2-Mini-NVFP4.gguf"},
        "source": "models/Inkling-2-Mini-NVFP4.gguf",
        "imatrix": "models/imatrix.gguf",
        "imatrix_default": True,
        "eval": {"dir": "data/eval", "ctx": 2048, "domains": {"wikitext": 8, "code": 4, "multilingual": 4}},
        "kld_dir": "kld",
        "llama": {"ngl": 99},
        "keep_variants": False,
        "variants": variants,
    }
    with open(a.out, "w") as f:
        f.write("# generated by python -m looptax.make_scan_config; do not edit by hand\n")
        yaml.safe_dump(cfg, f, sort_keys=False, width=200)
    print(f"{len(variants)} variants -> {a.out}")


if __name__ == "__main__":
    main()
