"""Generate the Phase 3 config: loop-aware vs uniform mixed precision at matched sizes.

The variable is the type of the gate/up experts (2/3 of all weights) per block. Down experts stay NVFP4 everywhere
(they cannot go below ~4.5 bpw with stock llama.cpp types, see notebook 2026-11-26), attention and embeddings stay as
in the reference (Q8_0). "NVFP4" for blocks 0-19 is the original weights copied bit for bit; blocks 20-23 (MXFP8 in
the release) are quantized to NVFP4.

Families (each traces a quality-vs-size curve):
  uniform     every block's gate_up at T
  loop-hi     loop blocks 6-17 NVFP4, prelude/coda gate_up at T
  edge-hi     prelude/coda NVFP4, loop blocks gate_up at T          (mirror of loop-hi, identical size)
  guided      per-block types chosen greedily from the Phase 2 scan  (added with --guided once the scan is in)

    python -m looptax.make_phase3_config --out configs/phase3_recipes.yaml [--guided results/phase2-scan/summary.csv]
"""

from __future__ import annotations

import argparse
import csv

import yaml

from . import recipes as R

LOW_TYPES = ["Q2_K", "IQ3_XXS", "Q3_K", "IQ4_XS"]
UNIFORM_TYPES = ["Q2_K", "IQ3_XXS", "Q3_K", "IQ4_XS", "Q4_K", "Q5_K"]
BASE = {"down": "NVFP4", "attn": "keep"}


def variant(vid: str, family: str, recipe: dict, table) -> dict:
    return {"id": vid, "family": family, "ftype": "Q8_0", "pure": True, "overrides": R.overrides(recipe, table),
            "est_gb": round(R.size_bytes(recipe, table) / 1e9, 3), "recipe": R.describe(recipe)}


def guided_recipes(scan_csv: str, table, targets_gb: list[float], qtype: str = "Q2_K",
                   family: str = "experts") -> list[tuple[str, dict]]:
    """Greedy allocation: start with every gate_up at `qtype`, then upgrade blocks to NVFP4 in order of measured
    sensitivity until the size target is reached. Sensitivity = Phase 2 KL when only that block's experts go to
    `qtype` (the recipe only changes expert types, so whole-block KL, which is partly attention, would mislead).
    Same budgets as the loop-hi curve."""
    rows = [r for r in csv.DictReader(open(scan_csv)) if r.get("family") == family and r.get("qtype") == qtype]
    assert len(rows) == 24, f"need experts-only scan for all 24 blocks, have {len(rows)}"
    sens = sorted(((float(r["kld_mean_avg"]), int(float(r["block"]))) for r in rows), reverse=True)
    out = []
    for target in targets_gb:
        upgraded: list[int] = []
        for _, b in sens:
            trial = R.make({"gate_up": qtype, **BASE}, {x: {"gate_up": "NVFP4"} for x in upgraded + [b]})
            if R.size_bytes(trial, table) / 1e9 > target:
                break
            upgraded.append(b)
        rec = R.make({"gate_up": qtype, **BASE}, {x: {"gate_up": "NVFP4"} for x in upgraded})
        out.append((f"guided-{target:.1f}gb", rec))
        print(f"guided {target:.2f} GB: NVFP4 gate_up in blocks {sorted(upgraded)}")
    return out


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="configs/phase3_recipes.yaml")
    ap.add_argument("--guided", help="Phase 2 summary.csv; adds sensitivity-guided recipes at the loop-hi sizes")
    a = ap.parse_args(argv)
    table = R.load_table()
    vs = []
    for t in UNIFORM_TYPES:
        vs.append(variant(f"uniform-{t.lower()}", "uniform", R.make({"gate_up": t, **BASE}), table))
    vs.append(variant("uniform-nvfp4", "uniform", R.make({"gate_up": "NVFP4", **BASE}), table))
    for t in LOW_TYPES:
        hi_loop = {b: {"gate_up": "NVFP4"} for b in R.LOOP}
        hi_edge = {b: {"gate_up": "NVFP4"} for b in R.EDGES}
        vs.append(variant(f"loop-hi-edges-{t.lower()}", "loop-hi", R.make({"gate_up": t, **BASE}, hi_loop), table))
        vs.append(variant(f"edge-hi-loop-{t.lower()}", "edge-hi", R.make({"gate_up": t, **BASE}, hi_edge), table))
    if a.guided:
        targets = [v["est_gb"] for v in vs if v["family"] == "loop-hi"]
        for vid, rec in guided_recipes(a.guided, table, targets):
            vs.append(variant(vid, "guided", rec, table))
    cfg = {
        "experiment": "phase3-recipes",
        "reference": {"id": "ref-nvfp4", "model": "models/Inkling-2-Mini-NVFP4.gguf"},
        "source": "models/Inkling-2-Mini-NVFP4.gguf",
        "imatrix": "models/imatrix.gguf",
        "imatrix_default": True,
        "eval": {"dir": "data/eval", "ctx": 2048, "domains": {"wikitext": 8, "code": 4, "multilingual": 4}},
        "llama": {"ngl": 99},
        "bench": {"pp": 512, "tg": 128, "reps": 3},
        "keep_variants": False,
        "variants": vs,
    }
    with open(a.out, "w") as f:
        f.write("# generated by python -m looptax.make_phase3_config; do not edit by hand\n")
        yaml.safe_dump(cfg, f, sort_keys=False, width=240)
    for v in vs:
        print(f"{v['id']:28s} {v['est_gb']:7.3f} GB")


if __name__ == "__main__":
    main()
