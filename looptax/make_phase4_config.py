"""Generate the Phase 4 config (bits x loop passes on TML-d24-varloop-research).

Reference and quantization source: our Q8_0 conversion of the varloop safetensors (scripts/convert_varloop.sh).
Bits axis: the Phase 3 "uniform" family (gate_up experts at T in every block, down experts NVFP4, attention Q8_0).
The reference itself is also run at every pass count (KL vs its own 3-pass logits = the effect of passes alone).

    python -m looptax.make_phase4_config --out configs/phase4_passes.yaml
"""

from __future__ import annotations

import argparse

import yaml

from . import recipes as R

TYPES = ["Q2_K", "Q3_K", "IQ4_XS", "NVFP4", "Q6_K"]
REF = "models/TML-d24-varloop-research-Q8_0-local.gguf"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="configs/phase4_passes.yaml")
    a = ap.parse_args(argv)
    table = R.load_table()
    vs = []
    for t in TYPES:
        rec = R.make({"gate_up": t, "down": "NVFP4", "attn": "keep"})
        vs.append({"id": f"uniform-{t.lower()}", "ftype": "Q8_0", "pure": True, "overrides": R.overrides(rec, table),
                   "est_gb": round(R.size_bytes(rec, table) / 1e9, 3), "gate_up": t})
    vs.append({"id": "reference-q8_0", "file": REF, "llama": {"ngl": None}, "gate_up": "Q8_0"})
    cfg = {
        "experiment": "phase4-passes",
        "reference": {"id": "varloop-q8_0", "model": REF, "llama": {"ngl": None}},
        "source": REF,
        "imatrix": "models/imatrix-TML-d24-varloop-research.gguf",   # ggml-org, computed with 3 passes
        "imatrix_default": True,
        "passes": [1, 2, 3, 4, 5],
        "eval": {"dir": "data/eval", "ctx": 2048, "domains": {"wikitext": 8, "code": 4}},
        "speed": {"pp": 512, "tg": 128, "ctx": 1024},
        "keep_variants": False,
        "variants": vs,
    }
    with open(a.out, "w") as f:
        f.write("# generated by python -m looptax.make_phase4_config; do not edit by hand\n")
        yaml.safe_dump(cfg, f, sort_keys=False, width=240)
    for v in vs:
        print(v["id"], v.get("est_gb"))


if __name__ == "__main__":
    main()
